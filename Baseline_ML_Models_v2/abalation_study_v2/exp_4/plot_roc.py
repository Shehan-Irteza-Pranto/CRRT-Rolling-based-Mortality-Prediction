"""
plot_roc.py — ROC curves (Day-1) for machine-only and combined DL models (best-seed exp_4 probabilities).
Two 300-dpi panels; each curve labelled with its AUROC. Reads roc_path{A,B}_1day.npz; the combined
Windowed-Transformer Fusion Stack curve uses the best-features (40 machine + 60 clinical) stack probs
regenerated by regenerate_stack_test_probs.py --n_machine 40 --n_clinical 60.
"""
import os
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from sklearn.metrics import roc_curve, roc_auc_score

_HERE = os.path.dirname(os.path.abspath(__file__))
PROB = os.path.join(_HERE, "results", "probs")
FIG = os.path.join(_HERE, "figures"); os.makedirs(FIG, exist_ok=True)
A = np.load(os.path.join(PROB, "roc_pathA_1day.npz"))
B = np.load(os.path.join(PROB, "roc_pathB_1day.npz"))

# best-features Windowed-Transformer Fusion Stack (40 machine + 60 clinical)
_stack = pd.read_csv(os.path.join(_HERE, "results", "combined_stack_test_probs_40x60_1day.csv"))
STACK_Y, STACK_P = _stack["label"].to_numpy(int), _stack["prob"].to_numpy(float)

# (display name, y, prob, is_ours)
MACHINE = [("CNN1D", A["yte"], A["machine_only_cnn1d"], False),
           ("RNN (BiGRU)", A["yte"], A["machine_only_rnn"], False),
           ("Transformer", A["yte"], A["machine_only_transformer"], False),
           ("Attention-CNN1D", B["yte"], B["attn"], True),
           ("Ensemble (ours)", B["yte"], B["ensemble"], True)]
COMBINED = [("CNN1D", A["yte"], A["combined_cnn1d"], False),
            ("RNN (BiGRU)", A["yte"], A["combined_rnn"], False),
            ("Transformer", A["yte"], A["combined_transformer"], False),
            ("Attn-CNN fusion (ours)", B["yte"], B["fusion"], True),
            ("Windowed-Transformer Fusion Stack (ours)", STACK_Y, STACK_P, True)]
COLORS = ["#7f8c8d", "#3498db", "#9b59b6", "#e67e22", "#c0392b"]


def panel(rows, title, out):
    fig, ax = plt.subplots(figsize=(6.6, 6.2))
    for (name, y, p, ours), col in zip(rows, COLORS):
        fpr, tpr, _ = roc_curve(y, p); au = roc_auc_score(y, p)
        ax.plot(fpr, tpr, color=col, lw=2.6 if ours else 1.7, ls="-" if ours else "--",
                label=f"{name} — AUROC {au:.3f}")
    ax.plot([0, 1], [0, 1], color="lightgray", lw=1, ls=":", label="chance")
    ax.set_xlim(-0.01, 1.01); ax.set_ylim(-0.01, 1.01)
    ax.set_xlabel("False-positive rate (1 − specificity)", fontsize=12)
    ax.set_ylabel("True-positive rate (sensitivity)", fontsize=12)
    ax.set_title(title, fontsize=11.5, fontweight="bold")
    ax.legend(loc="lower right", fontsize=8.5, frameon=True)
    ax.spines["top"].set_visible(False); ax.spines["right"].set_visible(False)
    ax.grid(alpha=0.2); fig.tight_layout()
    fig.savefig(out, dpi=300, bbox_inches="tight"); plt.close(fig); print(f"saved {out}", flush=True)


def main():
    panel(MACHINE, "ROC — machine-only models (1-day)",
          os.path.join(FIG, "roc_machine_only_1day.png"))
    panel(COMBINED, "ROC — combined models (1-day)",
          os.path.join(FIG, "roc_combined_1day.png"))


if __name__ == "__main__":
    main()
