"""
ensemble_ablation.py — preprocessing ablation of the BEST machine-only model (the ensemble)
==========================================================================================
Runs the same preprocessing ablation the parent study ran on single models (denoise-variant sweep +
leave-one-out), but on the **machine-only ensemble** (rich-classical GradientBoosting + RandomForest
+ attention-CNN1D, probability-averaged). For each cleaning configuration we rebuild the 200-feature
rich table and the CNN signal from that configuration's per-minute pressure, retrain, and report the
ensemble's held-out test AUROC (+ per-component) for 1-day and 2-day.

Reuses the proven `paper_materials/machine_only_pipeline.py` by overriding its pressure path and its
base-feature-table resolver per configuration. Base-133 tables come from the already-built
`exp_2/ablation/data/abalation/<tag>/machine_only/<case>/`; LOO per-minute streams are regenerated by
`gen_loo_streams.py`. Output: results/ablation_ensemble.csv (+ markdown).
"""
import os
import sys
import argparse
import warnings
import numpy as np
import pandas as pd

warnings.filterwarnings("ignore")
_HERE = os.path.dirname(os.path.abspath(__file__))
_AS_DIR = os.path.dirname(os.path.dirname(_HERE))                       # abalation_study_v2
sys.path.insert(0, _AS_DIR)
sys.path.insert(0, os.path.join(_AS_DIR, "paper_materials"))
from abl_config import DENOISE_VARIANTS                                  # noqa: E402
import machine_only_pipeline as M                                       # noqa: E402
from sklearn.metrics import roc_auc_score                              # noqa: E402

ABL_DATA = os.path.join(_AS_DIR, "exp_2", "ablation", "data", "abalation")
LOO_DIR = os.path.join(_HERE, "data")
RESULTS = os.path.join(_HERE, "results"); os.makedirs(RESULTS, exist_ok=True)

# (name, variant, peak, kind) — kind: 'denoise' or 'loo'
CONFIGS = []
for v in ["current", "Th70", "Th80", "Th90"]:
    for peak in ["denoised", "noised"]:
        CONFIGS.append((f"{v}_{peak}", v, peak, "denoise"))
for cfg in ["all3", "no_priming", "no_downtime", "no_peak"]:
    CONFIGS.append((f"loo_{cfg}", f"loo_{cfg}", "x", "loo"))

CNN_SEEDS = 3          # fewer seeds for the ablation sweep (relative comparison)


def _pressure_path(variant, peak, kind):
    if kind == "denoise":
        return DENOISE_VARIANTS[variant][peak]
    return os.path.join(LOO_DIR, f"pressure_{variant}.csv")   # variant == loo_<cfg>


def _base_table(variant, peak):
    tag = f"{variant}_{peak}"
    return lambda split, case: os.path.join(ABL_DATA, tag, "machine_only", case, f"{split}.csv")


def _ensemble(case):
    """Run both branches under the currently-set M.RAW_PRESSURE / M.machine_table; return a row."""
    A, yva, yte, pid_va, pid_te = M.branch_A(case)             # rich-classical (GB, RF)
    (dl_val, dl_test), yva_b, yte_b, _, _ = M.branch_B(case)   # attention-CNN1D
    assert np.array_equal(yte, yte_b)
    gb, rf = A["GradientBoosting"][1], A["RandomForest"][1]   # registry keys
    ens = np.mean([gb, rf, dl_test], axis=0)
    lo, hi = M._boot_ci(yte, ens, pid_te)
    return {"case": case,
            "ens_AUROC": round(roc_auc_score(yte, ens), 4), "ens_CI95": f"[{lo}, {hi}]",
            "richGB_AUROC": round(roc_auc_score(yte, gb), 4),
            "richRF_AUROC": round(roc_auc_score(yte, rf), 4),
            "cnn_AUROC": round(roc_auc_score(yte, dl_test), 4),
            "n_test": int(len(yte)), "n_pos": int(yte.sum())}


def run(cases=("1day", "2day")):
    # trim classical to the two ensemble members; use CNN_SEEDS for both branches (faster sweep)
    _orig_reg = M._classical_registry
    M._classical_registry = lambda: {k: v for k, v in _orig_reg().items()
                                     if k in ("GradientBoosting", "RandomForest")}
    M.N_SEEDS = CNN_SEEDS
    rows = []
    for name, variant, peak, kind in CONFIGS:
        press = _pressure_path(variant, peak, kind)
        if not os.path.exists(press):
            print(f"[skip] {name}: missing pressure {press}", flush=True); continue
        M.RAW_PRESSURE = press
        M.machine_table = _base_table(variant, peak)
        for case in cases:
            tbl = M.machine_table("test", case)
            if not os.path.exists(tbl):
                print(f"[skip] {name}/{case}: missing base table {tbl}", flush=True); continue
            try:
                row = _ensemble(case)
            except Exception as e:
                print(f"[err] {name}/{case}: {e}", flush=True); continue
            row = {"config": name, "variant": variant, "peak": peak, "kind": kind, **row}
            rows.append(row)
            pd.DataFrame(rows).to_csv(os.path.join(RESULTS, "ablation_ensemble.csv"), index=False)
            print(f"[ok] {name}/{case}: ENSEMBLE {row['ens_AUROC']} {row['ens_CI95']} "
                  f"(GB {row['richGB_AUROC']} RF {row['richRF_AUROC']} CNN {row['cnn_AUROC']})", flush=True)
    df = pd.DataFrame(rows)
    print("\n================ ablation on the machine-only ensemble ================")
    print(df.to_string(index=False))
    return df


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--cases", nargs="+", default=["1day", "2day"])
    a = ap.parse_args()
    run(tuple(a.cases))
